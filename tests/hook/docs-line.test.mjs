// ARC-09-C250, P4 — the banner's `Docs on disk:` line: the release family, the mode, and how many of the map's areas
// are on disk, naming the largest that are not. With it the Architect can say "not installed on this checkout" where
// it would otherwise say "not documented". It is not the status panel's `Docs:` line, which names the pin: the banner
// cannot check a pin without a spawn (ARC-08-C19), and it spawns nothing (ARC-09-S04, C199). So the line is made from
// reads alone: vendor/docs-map.md for the areas, a directory listing for what is on disk, the recorded mode, and
// engine.config.json for the family. Anything missing or unreadable means no line and no error.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire, syncBuiltinESMExports } from 'node:module';
import { dirname, join } from 'node:path';

import { bannerDocsLine } from '../../tools/snowarch/lib/docs/banner-line.mjs';
import { banner, MAX_AGE_MS } from '../../tools/snowarch/hooks/session-start.mjs';
import { statePath } from '../../tools/snowarch/lib/local-paths.mjs';
import { cachePath } from '../../tools/snowarch/lib/doctor-cache.mjs';
import { doctorCommand } from '../../tools/snowarch/lib/doctor/index.mjs';
import { greenTree, linkInstall, readJson, writeJson } from '../doctor/helpers/tree.mjs';
import { tempDir } from '../../tools/snowarch/tests/helpers/temp.mjs';

const MAP = 'vendor/docs-map.md';
const MARKDOWN = 'vendor/ServiceNowDocs/markdown';
const LABEL = 'Docs on disk: ';
const write = (path, text) => { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text); };
/** A map in the generator's shape: a header, then one row per area with its pages in the third cell. */
const mapOf = (areas) => ['<!-- GENERATED by scripts/gen-docs-map.mjs — do not edit -->',
  '# The documentation corpus map', '', '| Area | Title | Pages | Top products |', '|---|---|---|---|',
  ...Object.entries(areas).map(([a, pages]) => `| \`markdown/${a}/\` | ${a} title | ${pages} |  |`), ''].join('\n');
const FOUR = { alpha: 10, beta: 30, gamma: 20, delta: 5 };
/**
 * A corpus checkout's `.git`, as a submodule's gitlink file, pointing nowhere. Code that asks git about the corpus
 * (`sparseOf`, the status panel) then spawns, and fails without a side effect: without it, `sparseOf` returns before
 * its spawn, and the count below could not see the one regression it is for.
 */
const gitlink = (root) => write(join(root, 'vendor', 'ServiceNowDocs', '.git'), 'gitdir: ./no-such-gitdir\n');

/** A root with the map, the given areas on disk, the family, and a recorded docs state, or none. */
function rooted(t, { areas = FOUR, onDisk = Object.keys(areas), recorded = null } = {}) {
  const root = tempDir('snowarch-c250-docs-line-', t);
  write(join(root, MAP), mapOf(areas));
  gitlink(root);
  for (const a of onDisk) mkdirSync(join(root, MARKDOWN, a), { recursive: true });
  write(join(root, 'engine.config.json'), `${JSON.stringify({ docs: { family: 'australia' } })}\n`);
  if (recorded) write(statePath(root), `${JSON.stringify({ docs: recorded })}\n`);
  return root;
}

/**
 * Every child_process entry point, counted while `fn` runs, then put back. A PATH without git cannot prove "spawns
 * nothing" for this line: a git call whose failure is caught still prints a line, with a mode guessed from the
 * failure. The count can fail, and the case that makes the line call git once shows it does.
 */
const SPAWNERS = ['spawn', 'spawnSync', 'exec', 'execSync', 'execFile', 'execFileSync', 'fork'];
async function spawnsDuring(fn) {
  const cp = createRequire(import.meta.url)('node:child_process');
  const saved = Object.fromEntries(SPAWNERS.map((k) => [k, cp[k]]));
  const calls = [];
  for (const k of SPAWNERS) cp[k] = (...args) => { calls.push(`${k} ${args[0]}`); return saved[k](...args); };
  syncBuiltinESMExports();
  try {
    return { value: await fn(), calls };
  } finally {
    Object.assign(cp, saved);
    syncBuiltinESMExports();
  }
}

test('ARC-09-C250 — the whole corpus: the family, the mode, and every area of the map on disk', (t) => {
  const whole = `${LABEL}australia · full · 4/4 areas`;
  assert.equal(bannerDocsLine({ root: rooted(t, { recorded: { mode: 'full' } }) }), whole);
  // A folder the map does not list is not one of its areas: the count is the map's, never the listing's.
  const extra = rooted(t, { recorded: { mode: 'full' } });
  mkdirSync(join(extra, MARKDOWN, 'zeta'));
  assert.equal(bannerDocsLine({ root: extra }), whole);
});

test('ARC-09-C250 — sparse by choice: the line names the areas not installed, largest first', (t) => {
  const root = rooted(t, { onDisk: ['alpha', 'delta'], recorded: { mode: 'sparse', optIn: true } });
  assert.equal(bannerDocsLine({ root }), `${LABEL}australia · sparse · 2/4 — not installed: beta, gamma`);
});

test('ARC-09-C250 — past three, the three with most pages are named, a tie by name, and the rest counted', (t) => {
  const root = rooted(t, { areas: { a: 1, b: 60, c: 50, d: 50, e: 30, f: 20 }, onDisk: ['a'],
    recorded: { mode: 'sparse', optIn: true } });
  assert.equal(bannerDocsLine({ root }), `${LABEL}australia · sparse · 1/6 — not installed: b, c, d, +2`);
});

test('ARC-09-C250 — a switch to the whole corpus that has not finished: full, with the areas still missing', (t) => {
  const line = `${LABEL}australia · full · 2/4 — not installed: beta, gamma`;
  assert.equal(bannerDocsLine({ root: rooted(t, { onDisk: ['alpha', 'delta'], recorded: { mode: 'full' } }) }), line);
  // A recorded sparse without the optIn marker is the default an older release wrote, read as the whole corpus
  // (ARC-09-C244, `effectiveDocsMode`): the same switch, waiting for its next sync.
  assert.equal(bannerDocsLine({ root: rooted(t, { onDisk: ['alpha', 'delta'], recorded: { mode: 'sparse' } }) }), line);
});

test('ARC-09-C250 — with nothing recorded, the mode is what is on disk', (t) => {
  assert.equal(bannerDocsLine({ root: rooted(t) }), `${LABEL}australia · full · 4/4 areas`);
  assert.equal(bannerDocsLine({ root: rooted(t, { onDisk: ['beta'] }) }),
    `${LABEL}australia · sparse · 1/4 — not installed: gamma, alpha, delta`);
});

test('ARC-09-C250 — no map, an empty or garbled map, no corpus, no or bad config: no line and no error', (t) => {
  const CASES = [
    ['no map', (root) => rmSync(join(root, MAP))],
    ['an empty map', (root) => writeFileSync(join(root, MAP), '')],
    ['a map with no rows', (root) => writeFileSync(join(root, MAP), mapOf({}))],
    ['a directory where the map should be', (root) => { rmSync(join(root, MAP)); mkdirSync(join(root, MAP)); }],
    ['a garbled map', (root) => writeFileSync(join(root, MAP), '| `markdown/../` | x | many |\nnot | a | row\n')],
    ['no corpus on disk', (root) => rmSync(join(root, 'vendor/ServiceNowDocs'), { recursive: true })],
    ['no engine.config.json', (root) => rmSync(join(root, 'engine.config.json'))],
    ['an engine.config.json that does not parse', (root) => writeFileSync(join(root, 'engine.config.json'), '{')],
    ['no family', (root) => writeFileSync(join(root, 'engine.config.json'), '{"docs":{}}\n')],
    // A value read from a file never adds a banner line of its own.
    ['a family that is not a family name', (root) => writeFileSync(join(root, 'engine.config.json'),
      `${JSON.stringify({ docs: { family: 'australia\nLicence: ok' } })}\n`)],
  ];
  for (const [why, mutate] of CASES) {
    const root = rooted(t, { recorded: { mode: 'full' } });
    mutate(root);
    assert.equal(bannerDocsLine({ root }), null, why);
  }
});

test('ARC-09-C250 — the line is made from reads alone: no child process, on any shape', async (t) => {
  for (const shape of [{ recorded: { mode: 'full' } }, { onDisk: ['beta'] },
    { onDisk: ['alpha'], recorded: { mode: 'sparse', optIn: true } }]) {
    const root = rooted(t, shape);
    const { value, calls } = await spawnsDuring(() => bannerDocsLine({ root }));
    assert.ok((value ?? '').startsWith(LABEL), 'precondition: the shape prints a line');
    assert.deepEqual(calls, [], `the line spawned: ${JSON.stringify(shape)}`);
  }
});

/** A bootstrapped checkout with a doctor cache, then the corpus map and two of its four areas on disk. */
async function bootstrappedWithMap(t) {
  const root = linkInstall(greenTree(t, { mode: 'design' }));
  await doctorCommand({ flags: { quick: true, 'no-network': true, json: true },
    out: { write: () => {} }, cwd: root, input: { isTTY: false } });
  assert.ok(existsSync(cachePath(root)), 'precondition: the doctor wrote a cache');
  // After the doctor, so it never reads this hand-made corpus; the cache keys on no file under vendor/.
  write(join(root, MAP), mapOf(FOUR));
  gitlink(root);
  for (const a of ['alpha', 'delta']) mkdirSync(join(root, MARKDOWN, a), { recursive: true });
  return root;
}

/** Slower than the watchdog, and settling: a promise left pending ends the file's later cases (session-start.test). */
const hangs = (ms) => new Promise((resolve) => {
  setTimeout(() => resolve({ report: { modeLine: 'Mode: late' } }), ms);
});
/** The cache, made a day old: the fast path no longer answers, and the doctor's own lines are kept. */
const aged = (root) => {
  const cache = readJson(root, '.local/doctor-last.json');
  const at = new Date(Date.now() - MAX_AGE_MS - 60_000).toISOString();
  writeJson(root, '.local/doctor-last.json', { ...cache, at });
  return cache;
};
const doctorNotRun = () => { throw new Error('the doctor was imported'); };

test('ARC-09-C250 — every banner path prints the line after the Licence and Integrity lines', async (t) => {
  const PATHS = {
    cache: (root) => banner({ root, run: doctorNotRun }),
    rerun: (root) => {
      const { modeLine } = aged(root);
      return banner({ root, run: async () => ({ report: { modeLine } }) });
    },
    timeout: (root) => { aged(root); return banner({ root, watchdogMs: 50, run: () => hangs(300) }); },
    unbootstrapped: (root) => {
      rmSync(join(root, '.local'), { recursive: true, force: true });
      return banner({ root, run: async () => ({ report: {} }) });
    },
  };
  for (const [path, run] of Object.entries(PATHS)) {
    const root = await bootstrappedWithMap(t);
    const { family } = readJson(root, 'engine.config.json').docs;
    const result = await run(root);
    assert.equal(result.path, path);
    const ours = result.lines.filter((l) => l.startsWith(LABEL));
    assert.equal(ours.length, 1, `${path}: ${JSON.stringify(result.lines)}`);
    const at = result.lines.indexOf(ours[0]);
    assert.match(result.lines[at - 1] ?? '', /^(Licence|Integrity): /, `${path}: the line is out of place`);
    // The fixture records sparse without optIn, the whole corpus as C244 reads it; with no state, the disk decides.
    const mode = path === 'unbootstrapped' ? 'sparse' : 'full';
    assert.equal(ours[0], `${LABEL}${family} · ${mode} · 2/4 — not installed: beta, gamma`, path);
  }
});

test('ARC-09-C250 — the fast path, with the line, spawns no child process', async (t) => {
  const root = await bootstrappedWithMap(t);
  const { value, calls } = await spawnsDuring(() => banner({ root, run: doctorNotRun }));
  assert.equal(value.path, 'cache');
  assert.ok(value.lines.some((l) => l.startsWith(LABEL)), JSON.stringify(value.lines));
  assert.deepEqual(calls, []);
});

test('ARC-09-C250 — the hook, run as Claude Code runs it, prints the line with git off PATH', async (t) => {
  const root = await bootstrappedWithMap(t);
  const { family } = readJson(root, 'engine.config.json').docs;
  const empty = tempDir('snowarch-c250-no-git-', t);
  const r = spawnSync(process.execPath, [join(root, 'tools/snowarch/hooks/session-start.mjs')], {
    cwd: root, input: '{"hook_event_name":"SessionStart","source":"startup"}', encoding: 'utf8',
    env: { ...process.env, PATH: empty, Path: empty },
  });
  assert.equal(r.status, 0, r.stderr);
  assert.equal(r.stderr, '');
  assert.ok(r.stdout.split('\n').includes(`${LABEL}${family} · full · 2/4 — not installed: beta, gamma`), r.stdout);
});
