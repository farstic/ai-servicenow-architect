// The generated corpus recipe, in one place, rendered into three files.
//
// The recipe embeds the docs pin twice (`fetch`, `checkout --detach`), so it is generated rather
// than asserted — ARC-06's ruling, and `scripts/gen-docs-recipe.mjs` was its first consumer. The
// bump became the second (ARC-06-S05's fix), and ARC-06-S06 adds the two launcher files: the
// Node-free `bootstrap.sh` and `bootstrap.ps1` have to run the SAME git commands as the Node path,
// and a hand-copied shell function is a copy that drifts the first time the recipe changes.
//
// So: one module renders, three files receive, and a parity test diffs all of them. `docs sync
// --print-recipe` is the fourth reader of the same function, which is why it can be compared too.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { MODE, planRecipe, readAreas } from './sync.mjs';

export const RECIPE_TARGET = 'docs/ARCHITECTURE.md';
export const BEGIN = '<!-- DOCS-RECIPE:BEGIN (generated by scripts/gen-docs-recipe.mjs — do not edit) -->';
export const END = '<!-- DOCS-RECIPE:END -->';

/** The launcher marker pair. A comment in both languages, so one spelling serves both files. */
export const launcherBegin = (mode) => `# recipe-begin ${mode}`;
export const LAUNCHER_END = '# recipe-end';

/**
 * The three files, and the platform each is written FOR.
 *
 * The platform is fixed per target rather than read from `process.platform`: `bootstrap.ps1` is a
 * Windows launcher whether it is generated on a Mac or not, and a generated file whose content
 * depended on who ran the generator would fail its own `--check` on the next machine.
 */
export const TARGETS = Object.freeze([
  { id: 'architecture', path: RECIPE_TARGET, platform: 'linux', modes: [MODE.sparse], kind: 'markdown' },
  { id: 'sh', path: 'tools/snowarch/launcher/docs-recipe.sh', platform: 'linux',
    modes: [MODE.sparse, MODE.full], kind: 'launcher' },
  { id: 'ps1', path: 'tools/snowarch/launcher/docs-recipe.ps1', platform: 'win32',
    modes: [MODE.sparse, MODE.full], kind: 'launcher' },
]);

/** The commands themselves, for a fresh checkout. Every other function here is packaging. */
export function recipeLines({ config, areas, mode = MODE.sparse, platform = 'linux' }) {
  return planRecipe({ config, areas, mode, state: { present: false }, platform });
}

/** The markdown block: fenced, between HTML comment markers. */
export function renderRecipeBlock({ config, areas }) {
  const lines = recipeLines({ config, areas });
  return { block: [BEGIN, '', '```sh', ...lines, '```', '', END].join('\n'), commands: lines.length };
}

/** One `<begin>…<end>` region replaced. Returns null when the markers are not both present. */
function splice(doc, begin, end, body) {
  const start = doc.indexOf(begin);
  const stop = doc.indexOf(end, start + begin.length);
  if (start === -1 || stop === -1) return null;
  return doc.slice(0, start) + begin + body + doc.slice(stop);
}

/**
 * Render `target` against the current pin and splice it in.
 *
 *   written    the file changed (or would, with `write: false`)
 *   current    it already holds exactly this
 *   absent     no such file — a fixture tree, not a repository defect
 *   no-markers the file exists but has lost a marker, so nothing could be regenerated
 */
export function applyTarget(target, { root, config, areas = null, write = true }) {
  const path = join(root, target.path);
  if (!existsSync(path)) return { status: 'absent', target: target.id, path: target.path, commands: 0 };

  const resolved = areas ?? readAreas(root, config.docs.areasFile);
  const doc = readFileSync(path, 'utf8');
  let next = doc;
  let commands = 0;

  if (target.kind === 'markdown') {
    const { block, commands: n } = renderRecipeBlock({ config, areas: resolved });
    commands = n;
    const start = doc.indexOf(BEGIN);
    const stop = doc.indexOf(END);
    if (start === -1 || stop === -1 || stop < start) {
      return { status: 'no-markers', target: target.id, path: target.path, commands };
    }
    next = doc.slice(0, start) + block + doc.slice(stop + END.length);
  } else {
    // The file's OWN line ending, not this platform's. `.gitattributes` stores `*.ps1` as
    // `eol=crlf`, so `docs-recipe.ps1` arrives CRLF in every checkout on every OS — and a generator
    // that spliced LF into it would find the file different on the next `--check`, for ever, on a
    // clean tree. Detected from the file rather than assumed from the extension, so a future target
    // gets the same treatment without a second rule.
    const eol = doc.includes('\r\n') ? '\r\n' : '\n';
    for (const mode of target.modes) {
      const lines = recipeLines({ config, areas: resolved, mode, platform: target.platform });
      commands += lines.length;
      // Two-space indent inside the function body, and the marker lines themselves are preserved:
      // the launcher owns the function wrapper, the generator owns only what is between.
      const body = `${eol}${lines.map((l) => `  ${l}`).join(eol)}${eol}`;
      const spliced = splice(next, launcherBegin(mode), LAUNCHER_END, body);
      if (spliced === null) {
        return { status: 'no-markers', target: target.id, path: target.path, commands };
      }
      next = spliced;
    }
  }

  if (next === doc) return { status: 'current', target: target.id, path: target.path, commands };
  if (write) writeFileSync(path, next);
  return { status: 'written', target: target.id, path: target.path, commands };
}

/** Every target. The bump stages whatever came back `written`. */
export function applyAllTargets({ root, config, areas = null, write = true }) {
  return TARGETS.map((t) => applyTarget(t, { root, config, areas, write }));
}

/** Kept for the single-target callers that predate the launcher files. */
export function applyRecipeBlock({ root, config, areas = null, write = true }) {
  return applyTarget(TARGETS[0], { root, config, areas, write });
}
