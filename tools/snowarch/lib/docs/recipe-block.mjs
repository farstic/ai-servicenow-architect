// The generated recipe block in `docs/ARCHITECTURE.md`, in one place.
//
// The block embeds the docs pin twice (`fetch`, `checkout --detach`), so it is generated rather
// than asserted — that ruling is ARC-06's, and `scripts/gen-docs-recipe.mjs` was its first
// consumer. This module exists because the bump is the SECOND: `syncUpstream` moves the pin, and
// a block that still names the old one is stale from the instant the pin is written.
//
// Two callers, one definition. The markers, the fence and the splice are here and nowhere else —
// a second copy of "what the block looks like" is the same defect as the two definitions of the
// cone that ARC-03 shipped and had to unpick, and it fails the same way: silently, because both
// copies are individually plausible.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { planRecipe, readAreas } from './sync.mjs';

export const RECIPE_TARGET = 'docs/ARCHITECTURE.md';
export const BEGIN = '<!-- DOCS-RECIPE:BEGIN (generated by scripts/gen-docs-recipe.mjs — do not edit) -->';
export const END = '<!-- DOCS-RECIPE:END -->';

/**
 * The block, for a fresh sparse checkout, in POSIX form.
 *
 * `platform: 'linux'` is passed explicitly rather than left to the ambient process: Windows adds a
 * `core.longpaths` line, so one block cannot be byte-identical on both, and the document carries
 * the POSIX sequence with the Windows addition named in the prose beneath it. Generating from
 * `process.platform` would make the committed file depend on who ran the generator.
 */
export function renderRecipeBlock({ config, areas }) {
  const lines = planRecipe({ config, areas, mode: 'sparse', state: { present: false }, platform: 'linux' });
  return { block: [BEGIN, '', '```sh', ...lines, '```', '', END].join('\n'), commands: lines.length };
}

/**
 * Splice the block into the document.
 *
 * Returns a status rather than throwing, because the two callers want different things from the
 * same news: the generator turns `no-markers` into exit 2, while the bump has already moved the
 * pin by the time it asks and must report rather than abort half-done.
 *
 *   written    the block changed and the file was rewritten (or would be, with `write: false`)
 *   current    the file already holds this exact block
 *   absent     there is no such document — a fixture tree, not a repository defect
 *   no-markers the document exists but has lost its markers, so nothing could be regenerated
 */
export function applyRecipeBlock({ root, config, areas = null, write = true }) {
  const path = join(root, RECIPE_TARGET);
  if (!existsSync(path)) return { status: 'absent', path: RECIPE_TARGET, commands: 0 };

  const { block, commands } = renderRecipeBlock({
    config, areas: areas ?? readAreas(root, config.docs.areasFile),
  });
  const doc = readFileSync(path, 'utf8');
  const start = doc.indexOf(BEGIN);
  const stop = doc.indexOf(END);
  if (start === -1 || stop === -1 || stop < start) {
    return { status: 'no-markers', path: RECIPE_TARGET, commands };
  }

  const next = doc.slice(0, start) + block + doc.slice(stop + END.length);
  if (next === doc) return { status: 'current', path: RECIPE_TARGET, commands };
  if (write) writeFileSync(path, next);
  return { status: 'written', path: RECIPE_TARGET, commands };
}
