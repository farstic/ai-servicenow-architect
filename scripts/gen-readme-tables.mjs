#!/usr/bin/env node
/**
 * Generate the README's factual tables from the code, and check them in CI.
 *
 * P-30 is the reason this exists: the package's old `docs/INSTALLATION.md` documented OIDC/SSO,
 * `SNMCP_ORG_CONFIG`, `ALLOW_ANY_TABLE`, an `/auth/login` endpoint and an 11-step wizard
 * described as 5 — none of them implemented. Every one of those sentences was true of an
 * intention and false of the code, and prose has no way to notice. So the parts of the README
 * that are *facts about the build* are written by this script from `dist/contract.json` and
 * `dist/utils/permissions.js`, and `--check` fails CI when the committed text has drifted.
 *
 * What is NOT generated: the explanations. A generator can say there are 397 tools in 37
 * families; it cannot say why the SCRIPTING gate covers writes and not reads. Only the marked
 * blocks below are owned by this script; everything around them is written by a person.
 *
 *   node scripts/gen-readme-tables.mjs           # rewrite the blocks in place
 *   node scripts/gen-readme-tables.mjs --check   # exit 1 if the committed text differs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// `fileURLToPath`, never `new URL(...).pathname` — the latter is `/C:/…` on Windows, which is
// not a filesystem path (ARC-04-S12).
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = join(root, 'packages', 'snowarch');
const readmePath = join(pkg, 'README.md');

const contract = JSON.parse(readFileSync(join(pkg, 'dist', 'contract.json'), 'utf8'));

/** The prefix a tool name carries after `snow_`, e.g. `snow_core_records_query` → `core`. */
const familyOf = (name) => name.split('_')[1];

/** Longest first, so `now_assist` wins over `now`. Hand-written labels; the counts are not. */
const FAMILY_LABELS = {
  core: 'Core records, tables, CMDB, users, groups', inc: 'Incident', prb: 'Problem',
  chg: 'Change', cat: 'Service Catalog and requests', tsk: 'Task', csm: 'Customer Service',
  hr: 'HR Service Delivery', kb: 'Knowledge', itam: 'Asset and licence',
  cmdb: 'CMDB reconciliation and health', disco: 'Schema discovery', scr: 'Scripting objects',
  us: 'Update sets', studio: 'Scoped applications', atf: 'Automated Test Framework',
  flow: 'Flow Designer', orch: 'Orchestration playbooks', intg: 'Integrations and events',
  devops: 'DevOps Change Velocity', deploy: 'Deployment and packaging',
  sec: 'Security operations and GRC', usr: 'Users and groups administration',
  ntf: 'Notifications, email, attachments', cfg: 'System properties',
  rpt: 'Reports, scheduled jobs, logs', perf: 'Performance Analytics and dashboards',
  ml: 'Machine learning and predictions', na: 'Now Assist', nas: 'Now Assist skills',
  ai: 'AI agents', va: 'Virtual Agent', ws: 'Workspaces and UI Builder',
  portal: 'Service Portal', mob: 'Mobile', agile: 'Agile development', fluent: 'ServiceNow SDK',
};

function familiesBlock() {
  const counts = new Map();
  for (const t of contract.tools) {
    const f = familyOf(t.name);
    counts.set(f, (counts.get(f) ?? 0) + 1);
  }
  const rows = [...counts.entries()]
    .sort((a, b) => (b[1] - a[1]) || a[0].localeCompare(b[0]))
    .map(([f, n]) => `| \`snow_${f}_*\` | ${n} | ${FAMILY_LABELS[f] ?? '—'} |`);

  const unlabelled = [...counts.keys()].filter((f) => !FAMILY_LABELS[f]);
  if (unlabelled.length > 0) {
    // Loud, not silent. A new family with no label would otherwise ship as an em dash, and the
    // table would look complete while telling the reader nothing about a whole family.
    process.stderr.write(`gen-readme-tables: no label for family/families: ${unlabelled.join(', ')}\n`);
    process.exitCode = 1;
  }

  return [
    `**${contract.toolCount} tools in ${counts.size} families.** Counts come from`,
    '`dist/contract.json`; the table is generated by `scripts/gen-readme-tables.mjs`.',
    '',
    '| Family | Tools | What it covers |',
    '|---|---:|---|',
    ...rows,
  ].join('\n');
}

async function presetsBlock() {
  // Imported from the BUILT module, so this table is the one the server enforces rather than a
  // second copy of it in prose. `01` §6.3 and this block cannot disagree without CI noticing.
  const perms = await import(pathToFileURL(join(pkg, 'dist', 'utils', 'permissions.js')).href);
  const { PRESETS, FLAG_NAMES } = perms;

  const header = `| Preset | ${FLAG_NAMES.map((f) => `\`${f.replace('_ENABLED', '')}\``).join(' | ')} |`;
  const sep = `|---|${FLAG_NAMES.map(() => '---').join('|')}|`;
  const rows = Object.entries(PRESETS).map(([name, flags]) => {
    const cells = FLAG_NAMES.map((f) => (flags[f] === 'true' ? 'on' : 'off'));
    return `| \`${name}\` | ${cells.join(' | ')} |`;
  });

  return [
    'Presets are named flag sets. A flag is on only when it is the exact string `true`;',
    'anything else — `TRUE`, `1`, `yes`, unset — is off.',
    '',
    header, sep, ...rows,
    '',
    '`CMDB_WRITE`, `SCRIPTING`, `ATF` and `NOW_ASSIST` additionally require `WRITE`: a tool',
    'gated on one of them is refused while `WRITE` is off, and the refusal names `WRITE` first.',
  ].join('\n');
}

function errorCodesBlock() {
  const rows = contract.errorCodes
    .map(({ code, remedy }) => `| \`${code}\` | ${remedy || '—'} |`);
  return [
    `Every code the server can throw (${contract.errorCodes.length}), with what to do about it.`,
    'Generated from `src/errors/codes.ts` via `dist/contract.json`.',
    '',
    '| Code | Remedy |',
    '|---|---|',
    ...rows,
  ].join('\n');
}

const BLOCKS = {
  families: familiesBlock,
  presets: presetsBlock,
  'error-codes': errorCodesBlock,
};

/** Replace the body between the markers, keeping the markers themselves. */
function apply(text, name, body) {
  const start = `<!-- generated:${name} -->`;
  const end = `<!-- /generated:${name} -->`;
  const s = text.indexOf(start);
  const e = text.indexOf(end);
  if (s === -1 || e === -1) {
    throw new Error(`gen-readme-tables: missing marker pair for "${name}" in README.md`);
  }
  return `${text.slice(0, s + start.length)}\n\n${body}\n\n${text.slice(e)}`;
}

const check = process.argv.includes('--check');
const before = readFileSync(readmePath, 'utf8');
let after = before;
for (const [name, build] of Object.entries(BLOCKS)) {
  after = apply(after, name, await build());
}

if (!check) {
  writeFileSync(readmePath, after);
  process.stdout.write(`gen-readme-tables: wrote ${Object.keys(BLOCKS).length} blocks to README.md\n`);
} else if (after !== before) {
  // The message names the command, because "the README is stale" without it sends the reader
  // looking for which sentence to edit — and the answer is none of them.
  process.stderr.write(
    'gen-readme-tables: README.md generated blocks are stale.\n'
    + 'Run: node scripts/gen-readme-tables.mjs   and commit the result.\n'
    + 'Do not edit text between the <!-- generated:… --> markers by hand.\n');
  process.exit(1);
} else {
  process.stdout.write('gen-readme-tables: README.md generated blocks are current.\n');
}
