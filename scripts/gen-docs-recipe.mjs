#!/usr/bin/env node
// ARC-06 fix — the launcher recipe is GENERATED, because it embeds a value that moves.
//
// The block in `docs/ARCHITECTURE.md` carries the docs pin twice (`fetch`, `checkout --detach`), and
// `tests/docs-recipe.test.mjs` asserted it byte-for-byte against `--print-recipe`. That works until
// the pin moves — and then it fails on every bump pull request by construction, which is what
// happened on the first real one. A documentation block that embeds a moving value must be
// generated, not asserted: the parity guarantee is kept (the block IS the module's output) and the
// bump regenerates it along with the pin.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { planRecipe, readAreas } from '../tools/snowarch/lib/docs/sync.mjs';

const BEGIN = '<!-- DOCS-RECIPE:BEGIN (generated by scripts/gen-docs-recipe.mjs — do not edit) -->';
const END = '<!-- DOCS-RECIPE:END -->';
const TARGET = 'docs/ARCHITECTURE.md';

const argv = process.argv.slice(2);
const rootArg = argv.indexOf('--root');
const root = rootArg === -1
  ? resolve(dirname(fileURLToPath(import.meta.url)), '..')
  : resolve(argv[rootArg + 1]);
const check = argv.includes('--check');

const config = JSON.parse(readFileSync(join(root, 'engine.config.json'), 'utf8'));
const areas = readAreas(root, config.docs.areasFile);

// POSIX form. Windows adds one `core.longpaths` line, named in the prose beneath the block — a
// single block cannot be byte-identical on both platforms.
const lines = planRecipe({ config, areas, mode: 'sparse', state: { present: false }, platform: 'linux' });
const block = [BEGIN, '', '```sh', ...lines, '```', '', END].join('\n');

const path = join(root, TARGET);
const doc = readFileSync(path, 'utf8');
const start = doc.indexOf(BEGIN);
const stop = doc.indexOf(END);
if (start === -1 || stop === -1 || stop < start) {
  process.stderr.write(`gen-docs-recipe: markers not found in ${TARGET}\n`);
  process.exit(2);
}
const next = doc.slice(0, start) + block + doc.slice(stop + END.length);

if (check) {
  if (next !== doc) {
    process.stderr.write(`gen-docs-recipe: ${TARGET} recipe block is STALE — run node ${'scripts/gen-docs-recipe.mjs'} --write\n`);
    process.exit(1);
  }
  process.stdout.write(`gen-docs-recipe: ${TARGET} recipe block is current (${lines.length} commands)\n`);
  process.exit(0);
}
writeFileSync(path, next);
process.stdout.write(`gen-docs-recipe: wrote ${TARGET} (${lines.length} commands)\n`);
