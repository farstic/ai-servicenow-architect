#!/usr/bin/env node
// ARC-06-S10 — the sentences `bootstrap.sh` prints, generated into it.
//
// bash cannot read JSON, and the launcher must print the SAME sentences the Node path does — the
// remedies (S04), the closing block (S09) and ARC-03's network vocabulary. So they are generated
// into a marked region as shell assignments, `gen:check` keeps them current, and
// `tests/launcher-parity.test.mjs` compares every one against its source.
//
// This is the third consumer of the same rule the recipe taught: a sentence typed into a second
// file is a sentence that drifts, and the launcher is where a drift would be least visible — it
// runs on machines that have no Node to check it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const argv = process.argv.slice(2);
const rootArg = argv.indexOf('--root');
const root = rootArg === -1
  ? resolve(dirname(fileURLToPath(import.meta.url)), '..')
  : resolve(argv[rootArg + 1]);
const check = argv.includes('--check');

// Both launchers, because the sentences are the same and only the assignment syntax differs.
// `#` starts a comment in bash and in PowerShell alike, so one marker pair serves both.
export const TARGETS = Object.freeze([
  { path: 'bootstrap.sh', shell: 'bash' },
  { path: 'bootstrap.ps1', shell: 'powershell' },
]);
export const BEGIN = '# text-begin (generated by scripts/gen-launcher-text.mjs — do not edit)';
export const END = '# text-end';

const SENTENCE = await import(pathToFileURL(join(root, 'tools/snowarch/lib/net-sentences.mjs')).href);
const remedies = JSON.parse(readFileSync(join(root, 'tools/snowarch/lib/remedies.json'), 'utf8'));
const text = JSON.parse(readFileSync(join(root, 'tools/snowarch/lib/text.json'), 'utf8'));
const config = JSON.parse(readFileSync(join(root, 'engine.config.json'), 'utf8'));

/**
 * A single-quoted literal, per shell.
 *
 * bash escapes an embedded quote by leaving the string and re-entering it; PowerShell doubles it.
 * Both are literal otherwise — no interpolation, no backslash escapes — which is exactly what these
 * sentences need, since several of them contain `$`, `\` and backticks.
 */
const quote = (value, shell) => (shell === 'powershell'
  ? `'${String(value).replace(/'/g, "''")}'`
  : `'${String(value).replace(/'/g, `'\\''`)}'`);

/** The remedy for a check, on the platform bash will detect at run time. */
const remedy = (id, plat) => remedies[id][plat] ?? remedies[id].default;

/**
 * Which of these names a launcher actually mentions, outside the generated region.
 *
 * The region used to carry every sentence to both files, which meant `bootstrap.sh` declared the
 * `winget` remedies it can never print and `bootstrap.ps1` declared the `brew` ones — and BOTH
 * linters call an assigned-never-read variable a defect (SC2034, PSUseDeclaredVarsMoreThan-
 * Assignments). Deriving the list from the file's own references fixes that at the source and
 * cannot drift: a launcher that starts printing a sentence gets it on the next generate, and one
 * that stops loses it. `$NAME` and `${NAME}` are spelled the same way in bash and in PowerShell,
 * so one reader serves both.
 */
export function referencedNames(body) {
  const found = new Set();
  for (const m of body.matchAll(/\$\{?([A-Za-z_][A-Za-z0-9_]*)\}?/g)) found.add(m[1]);
  return found;
}

export function region({ shell = 'bash', remedies: r = remedies, text: t = text,
  sentences = SENTENCE, serverKey = config.mcp.serverKey, used = null } = {}) {
  // PowerShell needs a `$` and spaces around `=`; bash must have neither.
  const q = (v) => quote(v, shell);
  // `used === null` means "every sentence" — the shape the unit tests compare against. A caller
  // that passes a set gets only what its file mentions, and `null` for anything it does not.
  const set = (name, value) => {
    if (used && !used.has(name)) return null;
    return shell === 'powershell' ? `$${name} = ${q(value)}` : `${name}=${q(value)}`;
  };
  // The Windows launcher prints the Windows spellings; the sentences are otherwise identical.
  const next = shell === 'powershell' ? t.windows.nextDesign : t.posix.nextDesign;
  const lines = [
    BEGIN,
    set('SERVER_KEY', serverKey),
    set('MSG_NODE_DARWIN', remedy('node', 'darwin')),
    set('MSG_NODE_LINUX', remedy('node', 'linux')),
    set('MSG_NODE_WIN', remedy('node', 'win32')),
    set('MSG_GIT_DARWIN', remedy('git', 'darwin')),
    set('MSG_GIT_LINUX', remedy('git', 'linux')),
    set('MSG_GIT_WIN', remedy('git', 'win32')),
    set('MSG_CLAUDE', remedy('claudeCode', 'default')),
    set('MSG_NET', remedy('network', 'default')),
    set('MSG_DNS', sentences.dnsFailure('github.com')),
    set('MSG_TLS', sentences.tlsIntercepted({ tool: sentences.TOOL.git })),
    set('MSG_DOCTOR', t.doctorUnavailable),
    set('MSG_MODE', t.modeDesign),
    set('MSG_NEXT', next),
    set('MSG_CITATIONS', 'citations: not verified until Node 20+ is installed'),
    END,
  ];
  return lines.filter((line) => line !== null).join('\n');
}

/** Every name the region can define, in the order it defines them. */
export const NAMES = Object.freeze(
  region({ shell: 'bash' }).split('\n').slice(1, -1).map((line) => line.split('=')[0]));

let stale = [];
let checked = 0;
for (const target of TARGETS) {
  const path = join(root, target.path);
  let doc;
  try { doc = readFileSync(path, 'utf8'); } catch { continue; }   // a tree without it yet
  checked += 1;
  const start = doc.indexOf(BEGIN);
  const stop = doc.indexOf(END, start + BEGIN.length);
  if (start === -1 || stop === -1) {
    process.stderr.write(`gen-launcher-text: markers not found in ${target.path}\n`);
    process.exit(2);
  }
  // The file's OWN line endings: `.gitattributes` stores `*.ps1` as `eol=crlf`, so that file
  // arrives CRLF in every checkout and a generator splicing LF would report STALE for ever on a
  // clean tree — the lesson ARC-06-S06's recipe generator learned.
  const eol = doc.includes('\r\n') ? '\r\n' : '\n';
  // Read the references from the file MINUS the region, so last generate's own assignments do not
  // count as uses — otherwise the set could only ever grow, and a removed sentence would live for
  // ever on the strength of the line that defines it.
  const outside = doc.slice(0, start) + doc.slice(stop + END.length);
  const used = referencedNames(outside);
  const unknown = [...used].filter((n) => (n.startsWith('MSG_') || n === 'SERVER_KEY')
    && !NAMES.includes(n));
  if (unknown.length > 0) {
    process.stderr.write(`gen-launcher-text: ${target.path} mentions ${unknown.join(', ')}, `
      + 'which this generator does not define — a typo, or a sentence that needs adding here\n');
    process.exit(2);
  }
  const body = region({ shell: target.shell, used }).split('\n').join(eol);
  const next = doc.slice(0, start) + body + doc.slice(stop + END.length);
  if (next === doc) continue;
  if (check) { stale.push(target.path); continue; }
  writeFileSync(path, next);
  stale.push(target.path);
}

if (checked === 0) {
  process.stderr.write('gen-launcher-text: no launcher found\n');
  process.exit(2);
}
if (check) {
  if (stale.length > 0) {
    for (const p of stale) {
      process.stderr.write(`gen-launcher-text: ${p} text region is STALE — `
        + 'run node scripts/gen-launcher-text.mjs\n');
    }
    process.exit(1);
  }
  process.stdout.write(`gen-launcher-text: ${checked} launcher text region(s) current\n`);
  process.exit(0);
}
process.stdout.write(stale.length > 0
  ? `gen-launcher-text: wrote ${stale.join(', ')}\n`
  : `gen-launcher-text: no change to ${checked} launcher(s)\n`);
