#!/usr/bin/env node
// ARC-06-S10 — the sentences `bootstrap.sh` prints, generated into it.
//
// bash cannot read JSON, and the launcher must print the SAME sentences the Node path does — the
// remedies (S04), the closing block (S09) and ARC-03's network vocabulary. So they are generated
// into a marked region as shell assignments, `gen:check` keeps them current, and
// `tests/launcher-parity.test.mjs` compares every one against its source.
//
// This is the third consumer of the same rule the recipe taught: a sentence typed into a second
// file is a sentence that drifts, and the launcher is where a drift would be least visible — it
// runs on machines that have no Node to check it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const argv = process.argv.slice(2);
const rootArg = argv.indexOf('--root');
const root = rootArg === -1
  ? resolve(dirname(fileURLToPath(import.meta.url)), '..')
  : resolve(argv[rootArg + 1]);
const check = argv.includes('--check');

const TARGET = 'bootstrap.sh';
export const BEGIN = '# text-begin (generated by scripts/gen-launcher-text.mjs — do not edit)';
export const END = '# text-end';

const SENTENCE = await import(pathToFileURL(join(root, 'tools/snowarch/lib/net-sentences.mjs')).href);
const remedies = JSON.parse(readFileSync(join(root, 'tools/snowarch/lib/remedies.json'), 'utf8'));
const text = JSON.parse(readFileSync(join(root, 'tools/snowarch/lib/text.json'), 'utf8'));
const config = JSON.parse(readFileSync(join(root, 'engine.config.json'), 'utf8'));

/** A single-quoted shell string. The only escape bash needs inside one is the quote itself. */
const q = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

/** The remedy for a check, on the platform bash will detect at run time. */
const remedy = (id, plat) => remedies[id][plat] ?? remedies[id].default;

export function region({ remedies: r = remedies, text: t = text, sentences = SENTENCE,
  serverKey = config.mcp.serverKey } = {}) {
  const lines = [
    BEGIN,
    `SERVER_KEY=${q(serverKey)}`,
    `MSG_NODE_DARWIN=${q(remedy('node', 'darwin'))}`,
    `MSG_NODE_LINUX=${q(remedy('node', 'linux'))}`,
    `MSG_GIT_DARWIN=${q(remedy('git', 'darwin'))}`,
    `MSG_GIT_LINUX=${q(remedy('git', 'linux'))}`,
    `MSG_CLAUDE=${q(remedy('claudeCode', 'default'))}`,
    `MSG_NET=${q(remedy('network', 'default'))}`,
    `MSG_DNS=${q(sentences.dnsFailure('github.com'))}`,
    `MSG_TLS=${q(sentences.tlsIntercepted({ tool: sentences.TOOL.git }))}`,
    `MSG_DOCTOR=${q(t.doctorUnavailable)}`,
    `MSG_MODE=${q(t.modeDesign)}`,
    `MSG_NEXT=${q(t.posix.nextDesign)}`,
    `MSG_CITATIONS=${q('citations: not verified until Node 20+ is installed')}`,
    END,
  ];
  return lines.join('\n');
}

const path = join(root, TARGET);
const doc = readFileSync(path, 'utf8');
const start = doc.indexOf(BEGIN);
const stop = doc.indexOf(END, start + BEGIN.length);
if (start === -1 || stop === -1) {
  process.stderr.write(`gen-launcher-text: markers not found in ${TARGET}\n`);
  process.exit(2);
}
const next = doc.slice(0, start) + region() + doc.slice(stop + END.length);

if (check) {
  if (next !== doc) {
    process.stderr.write(`gen-launcher-text: ${TARGET} text region is STALE — `
      + 'run node scripts/gen-launcher-text.mjs\n');
    process.exit(1);
  }
  process.stdout.write(`gen-launcher-text: ${TARGET} text region is current\n`);
  process.exit(0);
}
writeFileSync(path, next);
process.stdout.write(`gen-launcher-text: ${next === doc ? 'no change to' : 'wrote'} ${TARGET}\n`);
