#!/usr/bin/env node
// ARC-08-C22 — the frame's `instance`/`store` help, generated from the dispatchers' own tables.
//
// `./snowarch instance --help` listed ONE sub-command — `add` — while the server CLI's own
// `instanceHelp()` lists nine. Both are real help texts for the same command; the one a user gets
// by typing the obvious thing was the poorer of the two, and it had no way to know about `list`,
// `test`, `set-credentials`, `set-preset`, `set-flags`, `set-default`, `remove` or `import`. The
// store's was the same shape, three sub-commands written in three places.
//
// WHY A GENERATOR AND NOT AN IMPORT. The frame runs in design-only, where `node_modules` does not
// exist; `dist/cli/instance-command.js` reaches `zod` and `undici` through its import graph, so a
// frame that imported the help would fail on exactly the installs the frame exists to serve. The
// generator runs where the dependencies are, writes the lines into a marked region, and `gen:check`
// fails the build when the two drift — the same arrangement `gen-launcher-text` uses for the
// sentences bash has to print without Node.
//
// Usage: node scripts/gen-cli-help.mjs [--check] [--root <dir>]
// Exit 0 written / current · 1 stale (with --check) · 2 cannot run.
import { readFileSync, writeFileSync, writeSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const argv = process.argv.slice(2);
const rootArg = argv.indexOf('--root');
const root = rootArg === -1
  ? resolve(dirname(fileURLToPath(import.meta.url)), '..')
  : resolve(argv[rootArg + 1]);
const check = argv.includes('--check');

const die = (m) => { writeSync(2, `gen-cli-help: ${m}\n`); process.exit(2); };

export const BEGIN = '// help-begin (generated by scripts/gen-cli-help.mjs — do not edit)';
export const END = '// help-end';

/**
 * The two frames and where their sub-command lines come from.
 *
 * `tail` is the frame's own sentence and is NOT generated: "everything after this word belongs to
 * the server CLI" is a fact about the frame, not about the dispatcher, and the dispatcher's help
 * has no reason to know it.
 */
export const TARGETS = Object.freeze([
  { path: 'tools/snowarch/lib/instance.mjs', lines: 'instanceSubCommandLines', word: 'instance' },
  { path: 'tools/snowarch/lib/store.mjs', lines: 'storeSubCommandLines', word: 'store' },
]);

/**
 * ONE MODULE, AND IT IMPORTS NOTHING.
 *
 * The first version imported `dist/cli/instance-command.js` and `dist/cli/store-command.js` for
 * their `instanceHelp()`/`storeHelp()`. Both reach `zod` and `undici` through their graphs, so
 * `gen-all --check` died on a clone with no `node_modules` — which `tests/gen-all.test.mjs` asserts
 * must stay clean, and which is precisely the install the frame's own help exists for. The tables
 * and their layout moved to `cli/help-tables.ts`, which has no imports at all; both dispatchers
 * read them from there, so this generator and the product cannot diverge.
 */
export const TABLES = 'packages/snowarch/dist/cli/help-tables.js';

/** The generated region: a `USAGE` array body the frame joins with newlines. */
export function region(lines, word) {
  const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  return [
    BEGIN,
    `  ${quote(`usage: ./snowarch ${word} <command> [options]`)},`,
    "  '',",
    ...lines.map((l) => `  ${quote(l)},`),
    END,
  ].join('\n');
}

/**
 * Run only when this file IS the command — ARC-08-C20's lesson, which I had to learn twice.
 *
 * That script generated its fixtures at import time and called `process.exit()`, so the test that
 * imported its helpers ran one case and vanished with a clean exit: `pass 1`, four assertions gone.
 * This file was written a day later and did the same thing, and `tests/cli-help.test.mjs` reported
 * `pass 1` for the same reason. A file that both exports and executes cannot be tested, and the
 * guard belongs in every generator, not in the one where it was first needed.
 */
const INVOKED_DIRECTLY = process.argv[1]
  && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (INVOKED_DIRECTLY) await main();

async function main() {
let stale = 0;
const tables = await import(pathToFileURL(join(root, TABLES)).href)
  .catch((e) => die(`${TABLES} is not loadable — run \`npm run build:dist\` (${e.message})`));

for (const target of TARGETS) {
  const lines = tables[target.lines]?.();
  if (!lines?.length) die(`${TABLES} does not export ${target.lines}()`);

  const path = join(root, target.path);
  const source = readFileSync(path, 'utf8');
  const begin = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  if (begin === -1 || end === -1) die(`${target.path} has no generated region`);

  const next = `${source.slice(0, begin)}${region(lines, target.word)}${source.slice(end + END.length)}`;
  if (next === source) {
    writeSync(1, `gen-cli-help: ${target.path} is current (${lines.length} sub-commands)\n`);
    continue;
  }
  if (check) {
    stale += 1;
    writeSync(1, `gen-cli-help: ${target.path} is stale — run \`npm run gen\` and commit the result\n`);
    continue;
  }
  writeFileSync(path, next);
  writeSync(1, `gen-cli-help: wrote ${target.path} (${lines.length} sub-commands)\n`);
}
process.exit(stale > 0 ? 1 : 0);
}
