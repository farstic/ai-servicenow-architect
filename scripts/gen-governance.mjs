#!/usr/bin/env node
/**
 * Generate the governance texts that must agree with the server contract.
 *
 * §2.1's write gate was keyed on a tool-name prefix that had changed (P-05), and §2.2 was stated in
 * four documents in two naming generations (P-33). Both are the same failure: a rule about the
 * server, written by hand, in more than one place. Here the rule is rendered from
 * `dist/contract.json` and `engine.config.json`, and `--check` fails CI when the committed text is
 * not what they produce.
 *
 * Usage:
 *   node scripts/gen-governance.mjs                 write every target
 *   node scripts/gen-governance.mjs --check         exit 1 with a unified diff if any is stale
 *   node scripts/gen-governance.mjs --only rule     one target (repeat or comma-separate)
 *
 * Exit 0 written/current · 1 stale · 2 cannot run.
 *
 * A renderer is `packages/contract/gen/<name>.mjs` exporting `render(ctx) -> string` and `target`.
 * Exporting `markers` as well makes it a block-in-file target: only the text between the two marker
 * lines is replaced and the rest of the file is left byte-identical, which is how a generated table
 * lives inside a hand-written page.
 *
 * Stdlib only: this runs in `npm run lint` on every cell, before anything is installed.
 */
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { unifiedDiff } from './lib/diff.mjs';

const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const value = (name) => {
  const i = argv.indexOf(name);
  return i === -1 ? undefined : argv[i + 1];
};

// `fileURLToPath`, never `new URL(...).pathname` — the latter is `/C:/…` on Windows.
const selfRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(value('--root') ?? selfRoot);
const CHECK = flag('--check');
const only = (value('--only') ?? '').split(',').map((s) => s.trim()).filter(Boolean);

const RENDERERS = ['rule-file', 'presets'];
// `--only rule` reads better than `--only rule-file` and is what the story writes.
const ALIAS = { rule: 'rule-file', presets: 'presets' };

const cannotRun = (message) => { process.stderr.write(`gen-governance: ${message}\n`); process.exit(2); };
const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');

const contractPath = 'packages/snowarch/dist/contract.json';
if (!existsSync(join(ROOT, contractPath))) {
  cannotRun(`${contractPath} is missing — it is a build artefact; run node scripts/build-dist.mjs`);
}
if (!existsSync(join(ROOT, 'engine.config.json'))) cannotRun('engine.config.json is missing');

let ctx;
try {
  const contractText = read(contractPath);
  const config = JSON.parse(read('engine.config.json'));
  const serverKey = config?.mcp?.serverKey;
  if (typeof serverKey !== 'string' || !serverKey) {
    cannotRun('engine.config.json has no mcp.serverKey — the tool prefix has no source');
  }
  ctx = {
    root: ROOT,
    contract: JSON.parse(contractText),
    // The sha of the bytes on disk, not of a re-serialisation: the pin compares the same bytes.
    sha: createHash('sha256').update(contractText).digest('hex'),
    serverKey,
  };
} catch (e) {
  cannotRun(`could not read an input: ${e.message}`);
}

const selected = only.length > 0 ? only.map((o) => ALIAS[o] ?? o) : RENDERERS;
const unknown = selected.filter((s) => !RENDERERS.includes(s));
if (unknown.length > 0) cannotRun(`--only names unknown target(s): ${unknown.join(', ')}`);

/**
 * The generated-file header.
 *
 * It carries the contract sha, so ANY contract change is a byte diff on every generated file and
 * ARC README criterion 2 holds without the renderer having to notice what changed. It names the
 * module to edit, because the first instinct on reading a generated file is to edit the file.
 */
const headerFor = (module) => `<!-- GENERATED by scripts/gen-governance.mjs from ${contractPath} `
  + `(sha256 ${ctx.sha.slice(0, 12)}) — do not edit; edit packages/contract/gen/${module}.mjs `
  + 'and run npm run gen -->';

async function load(name) {
  const mod = await import(new URL(`../packages/contract/gen/${name}.mjs`, import.meta.url));
  if (typeof mod.render !== 'function' || typeof mod.target !== 'string') {
    cannotRun(`${name}.mjs must export render(ctx) and target`);
  }
  return mod;
}

/** The rendered bytes for a whole-file target, or the new whole file for a block target. */
function compose(mod, name, current) {
  // A renderer that cannot produce output is "cannot run", not "stale": the contract lost something
  // it names, and the useful output is one line saying which — not a stack trace on a CI cell.
  let body;
  try {
    body = mod.render({ ...ctx, header: headerFor(name) });
  } catch (e) {
    cannotRun(`${name}: ${e.message}`);
  }
  if (!mod.markers) {
    // Whole-file targets end with exactly one newline, like every other file in the repository.
    return `${body.replace(/\n+$/, '')}\n`;
  }
  if (current === null) {
    cannotRun(`${name}: ${mod.target} does not exist — a block target edits a hand-written file`);
  }
  const lines = current.split('\n');
  const begin = lines.findIndex((l) => mod.markers.begin.test(l));
  const end = lines.findIndex((l) => mod.markers.end.test(l));
  if (begin === -1 || end === -1 || end < begin) {
    cannotRun(`${name}: markers not found in ${mod.target} — see ARC-02 S09`);
  }
  // Both marker lines are kept and NOTHING is padded around the body: the block sits inside a
  // hand-written page whose line budget is a criterion, and a generator that adds two blank lines
  // on its first run has changed a document it was supposed to leave alone.
  return [...lines.slice(0, begin + 1), ...body.split('\n'), ...lines.slice(end)].join('\n');
}

const results = [];
for (const name of selected) {
  const mod = await load(name);
  const abs = join(ROOT, mod.target);
  const current = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
  const next = compose(mod, name, current);
  // LF-normalised comparison: a Windows checkout with `core.autocrlf` is not a diff to act on.
  const stale = current === null || current.replace(/\r\n/g, '\n') !== next;
  results.push({ name, target: mod.target, abs, current, next, stale });
}

if (CHECK) {
  const stale = results.filter((r) => r.stale);
  for (const r of stale) {
    process.stdout.write(`${unifiedDiff((r.current ?? '').replace(/\r\n/g, '\n'), r.next, r.target)}\n`);
  }
  if (stale.length > 0) {
    process.stdout.write(`gen-governance: ${stale.length} target(s) stale — run npm run gen and commit the result\n`);
    process.exit(1);
  }
  process.stdout.write(`gen-governance: ${results.length} target(s) current (contract ${ctx.sha.slice(0, 12)})\n`);
  process.exit(0);
}

for (const r of results) {
  if (!r.stale) continue;
  mkdirSync(dirname(r.abs), { recursive: true });
  writeFileSync(r.abs, r.next);
}
const written = results.filter((r) => r.stale).map((r) => r.target);
process.stdout.write(written.length === 0
  ? `gen-governance: ${results.length} target(s) already current\n`
  : `gen-governance: wrote ${written.join(', ')}\n`);
